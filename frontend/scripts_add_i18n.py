def merge(dst: dict, src: dict) -> None:
    """Recursively merge src into dst without touching existing keys."""
    for key, value in src.items():
        if key in dst and isinstance(dst[key], dict) and isinstance(value, dict):
            merge(dst[key], value)
        elif key not in dst:
            dst[key] = value


